"""Tables from results/results.json -> results/tables.md.

    python -m experiments.make_tables

Iteration counts are parameter updates. `own` = the five methods of lr_opt; `scipy` = the same
problem solved with scipy.optimize.minimize for CG, BFGS and L-BFGS-B (GD and NR have no scipy
counterpart, so these rows repeat the `own` runs).
"""
import json

from experiments.run import ROOT
from lr_opt import OPTIMIZERS

NAMES = {"breast": "Breast Cancer Wisconsin", "prostate": "Prostate Cancer"}
OPTS = list(OPTIMIZERS)
PROTOCOLS = ("own", "scipy")


def yn(b):
    return "Yes" if b else "No"


def optimization_table(res, proto, key):
    rows = ["| Optimizer | Final cost | ‖∇J‖₂ | Iter. | f / ∇f / ∇²f evals | Time (ms) | ‖∇J‖₂ < tol | Solver success |",
            "|---|---|---|---|---|---|---|---|"]
    for k in OPTS:
        r = res["runs"][proto][key][k]
        rows.append(f"| {k} | {r['fun']:.6f} | {r['grad_norm']:.1e} | {r['n_iter']} | {r['nfev']} / {r['ngev']} / {r['nhev']} "
                    f"| {1000 * r['time']:.2f} | {yn(r['converged'])} | {yn(r['success'])} |")
    return rows


def metrics_row(m):
    return (f"{m['accuracy']:.2f} | {m['auc']:.4f} | {m['precision']:.4f} | {m['sensitivity']:.4f} | "
            f"{m['specificity']:.4f} | {m['f1']:.4f} | {m['log_loss']:.4f}")


def tables(results):
    out = ["# Results", "",
           "Generated by `python -m experiments.make_tables` from `results/results.json`.",
           "`own` = all five methods from `lr_opt`; `scipy` = CG, BFGS and L-BFGS-B through `scipy.optimize.minimize` "
           "(`gtol=1e-6`), with GD and NR from `lr_opt`. Iterations are parameter updates. Times are medians of 5 "
           "runs on this machine.", ""]
    for ds, res in results.items():
        lam = res["cv"]["selected"]
        out += [f"## {NAMES[ds]} (n_train = {res['n_train']}, n_test = {res['n_test']}, p = {len(res['features'])})", "",
                "Cross-validation (mean validation log-loss): " +
                ", ".join(f"λ={g:g}: {s:.4f}" for g, s in zip(res["cv"]["grid"], res["cv"]["mean_log_loss"])) +
                f" → **λ = {lam:g}**.", "",
                f"Training set linearly separable (LP check): **{yn(res['train_separable'])}**.", ""]
        for proto in PROTOCOLS:
            out += [f"### Optimization at λ = {lam:g}, `{proto}`", ""]
            out += optimization_table(res, proto, "selected") + [""]
        out += [f"### Test metrics, λ = 0 vs. λ = {lam:g}", "",
                "| Runs | Optimizer | λ | Acc. (%) | AUC | Precision | Sensitivity | Specificity | F1 | Log-loss | ‖b‖₂ | Train acc. (%) |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for proto in PROTOCOLS:
            for k in OPTS:
                for key, lam_k in (("0", 0.0), ("selected", lam)):
                    r = res["runs"][proto][key][k]
                    out.append(f"| {proto} | {k} | {lam_k:g} | {metrics_row(r['metrics'])} | {r['coef_norm']:.1f} | "
                               f"{r['train_accuracy']:.2f} |")
        out += ["", "### Optimization at λ = 0, `own`", ""] + optimization_table(res, "own", "0") + [""]
        out += [f"### Bootstrap 95% CI, Newton–Raphson at λ = {lam:g} (2,000 resamples of the test set)", "",
                "| Metric | Estimate | 95% CI |", "|---|---|---|"]
        for m, (e, lo, hi) in res["bootstrap"].items():
            out.append(f"| {m} | {e:.4f} | [{lo:.4f}, {hi:.4f}] |")
        out.append("")
    return "\n".join(out)


def main():
    results = json.loads((ROOT / "results" / "results.json").read_text())
    (ROOT / "results" / "tables.md").write_text(tables(results), encoding="utf-8")
    print("wrote results/tables.md")


if __name__ == "__main__":
    main()

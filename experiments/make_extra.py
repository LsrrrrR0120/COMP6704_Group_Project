"""Tables and figures for results/extra.json -> results/extra.md, figures/{ablation,order,splits,scaling}.*

    python -m experiments.make_extra

Standard deviations are population standard deviations (ddof = 0) over the 20 splits.
"""
import json

import matplotlib.pyplot as plt
import numpy as np

from experiments.make_figures import COLORS, save
from experiments.make_tables import NAMES, OPTS
from experiments.run import ROOT

DEFAULT_VARIANTS = {"GD": "GD, a = 0.1 (default)", "NR": "NR, pure (default)", "CG": "CG, FR (default)",
                  "L-BFGS": "L-BFGS, m = 10 (default)"}


def ms(x):
    return f"{np.mean(x):.2f} ± {np.std(x):.2f}"


def markdown(E):
    out = ["# Additional experiments", "", "Generated by `python -m experiments.make_extra` from `results/extra.json`.",
           "Standard deviations over splits use ddof = 0.", ""]
    out += ["## Ablation at the selected λ (no iteration cap)", "",
            "| Variant | " + " | ".join(f"{NAMES[d]}: iter. / f-evals / time (ms)" for d in E["ablation"]) + " |",
            "|---|" + "---|" * len(E["ablation"])]
    for v in next(iter(E["ablation"].values())):
        cells = [f"{r['n_iter']} / {r['nfev']} / {1000 * r['time']:.2f}" for r in (E["ablation"][d][v] for d in E["ablation"])]
        out.append(f"| {v} | " + " | ".join(cells) + " |")
    out += ["", "## Curvature at the minimizer and the rate of fixed-step GD (a = 0.1)", "",
            "| Dataset | μ* | L* | κ* = L*/μ* | global bound L | predicted rate (1 − ...)² | measured rate | GD iterations to tol |",
            "|---|---|---|---|---|---|---|---|"]
    for d, r in E["rates"].items():
        out.append(f"| {NAMES[d]} | {r['mu']:.4f} | {r['L']:.4f} | {r['kappa']:.1f} | {r['L_global']:.3f} | "
                   f"{r['gd_predicted_rate']:.5f} | {r['gd_measured_rate']:.5f} | {r['gd_iterations_to_tol']} |")
    out += ["", "## 20 random 70/30 splits (full pipeline, `own` implementations)", ""]
    for d, S in E["splits"].items():
        lams = {}
        for row in S:
            lams[row["lam"]] = lams.get(row["lam"], 0) + 1
        out += [f"### {NAMES[d]}", "",
                "Selected λ: " + ", ".join(f"{l:g} ({c}×)" for l, c in sorted(lams.items())) +
                f". Training set separable in {sum(r['separable'] for r in S)} of {len(S)} splits.", "",
                "| Optimizer | iterations | time (ms) | strictly converged | accuracy (%) | AUC | log-loss |",
                "|---|---|---|---|---|---|---|"]
        for k in OPTS:
            R = [row["runs"][k] for row in S]
            out.append(f"| {k} | {ms([r['n_iter'] for r in R])} | {ms([1000 * r['time'] for r in R])} | "
                       f"{sum(r['converged'] for r in R)}/{len(R)} | {ms([r['accuracy'] for r in R])} | "
                       f"{np.mean([r['auc'] for r in R]):.4f} ± {np.std([r['auc'] for r in R]):.4f} | "
                       f"{np.mean([r['log_loss'] for r in R]):.4f} ± {np.std([r['log_loss'] for r in R]):.4f} |")
        out.append("")
    out += ["## Scaling with the dimension (synthetic, n = 4000, λ = 1)", "",
            "| d | " + " | ".join(f"{k}: iter. / time (s)" for k in OPTS) + " |", "|---|" + "---|" * len(OPTS)]
    for d, row in E["scaling"].items():
        out.append(f"| {d} | " + " | ".join(f"{row[k]['n_iter']} / {row[k]['time']:.3f}" for k in OPTS) + " |")
    return "\n".join(out) + "\n"


def fig_ablation(E):
    fig, axes = plt.subplots(1, 3, figsize=(9.6, 2.9), layout="constrained")
    abl = E["ablation"]["breast"]
    f_star = min(min(v["history"]["f"]) for v in abl.values())
    styles = {"GD, a = 0.01": ":", "GD, a = 0.1 (default)": "-", "GD, a = 1/L": "--", "GD, Armijo": "-."}
    for v, ls in styles.items():
        f = np.maximum(np.array(abl[v]["history"]["f"]) - f_star, 1e-16)
        axes[0].loglog(np.arange(1, len(f) + 1), f, ls=ls, color=COLORS["GD"], lw=1.4,
                       label=v[4:].replace(" (default)", ""))
    axes[0].axvline(8000, color="0.5", lw=0.8)
    axes[0].annotate("cap of the\nmain runs\n(8,000)", (8000, 0.3), xytext=(4, 0), textcoords="offset points",
                     ha="left", va="top", fontsize=7, color="0.35")
    axes[0].set(xlabel="iteration + 1", ylabel="J(b) − J*", title="(a) GD step size, breast cancer")
    axes[0].legend(loc="lower left", fontsize=7)

    ms_ = [1, 3, 5, 10, 20, 50]
    for d, marker in (("breast", "o"), ("prostate", "s")):
        it = [E["ablation"][d][f"L-BFGS, m = {m}" + (" (default)" if m == 10 else "")]["n_iter"] for m in ms_]
        axes[1].plot(ms_, it, marker=marker, color=COLORS["L-BFGS"], mfc="none", lw=1.3, label=NAMES[d])
    axes[1].set_xscale("log")
    axes[1].set_xticks(ms_, [str(m) for m in ms_])
    axes[1].set(xlabel="memory m", ylabel="iterations", title="(b) L-BFGS memory", ylim=(0, None))
    axes[1].legend(loc="lower left", fontsize=7)

    variants = ["CG, FR (default)", "CG, FR, restart every d", "CG, PR+", "CG, PR+, restart every d"]
    for x, v in enumerate(variants):
        for j, (d, hatch) in enumerate((("breast", None), ("prostate", "///"))):
            axes[2].bar(x + (j - 0.5) * 0.4, E["ablation"][d][v]["n_iter"], width=0.4, color=COLORS["CG"],
                        edgecolor="white", hatch=hatch)
    axes[2].bar([0], [0], color="0.6", label="breast")
    axes[2].bar([0], [0], color="0.6", hatch="///", edgecolor="white", label="prostate")
    axes[2].set_xticks(range(len(variants)), ["FR", "FR + restart", "PR+", "PR+ + restart"], fontsize=7)
    axes[2].set(ylabel="iterations", title="(c) CG coefficient and restarts")
    axes[2].grid(axis="x", visible=False)
    axes[2].legend(loc="upper left", fontsize=7)
    save(fig, "ablation")


def fig_order(E, lam):
    """||g_{k+1}|| against ||g_k||: slope 1 = linear, slope 2 = quadratic convergence."""
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.0), layout="constrained")
    for ax, d in zip(axes, ("breast", "prostate")):
        for k in OPTS:
            g = np.array(E["ablation"][d][DEFAULT_VARIANTS[k]]["history"]["grad_norm"])
            if k == "GD":
                g = g[:: max(1, len(g) // 300)]
            ax.loglog(g[:-1], g[1:], ".-" if k != "GD" else "-", ms=3, lw=1, color=COLORS[k], label=k)
        lo, hi = 1e-9, 2
        t = np.logspace(np.log10(lo), np.log10(hi), 10)
        ax.loglog(t, t, color="0.6", lw=0.8, ls="--")
        ax.loglog(t, t**2, color="0.6", lw=0.8, ls=":")
        ax.annotate("slope 1", (1e-8, 1e-8), xytext=(4, -10), textcoords="offset points", fontsize=7, color="0.4")
        ax.annotate("slope 2", (1e-3, 1e-6), xytext=(4, -2), textcoords="offset points", fontsize=7, color="0.4")
        ax.set(xlim=(lo, hi), ylim=(1e-12, hi), xlabel="‖∇J(b_k)‖₂", ylabel="‖∇J(b_{k+1})‖₂",
               title=f"{NAMES[d]}, λ = {lam[d]:g}")
    axes[1].legend(loc="upper left", bbox_to_anchor=(1.0, 1.0))
    save(fig, "order")


def fig_splits(E):
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.8), layout="constrained")
    for ax, d in zip(axes, ("breast", "prostate")):
        S = E["splits"][d]
        data = [[row["runs"][k]["n_iter"] for row in S] for k in OPTS]
        bp = ax.boxplot(data, patch_artist=True, widths=0.6, medianprops=dict(color="black"))
        for patch, k in zip(bp["boxes"], OPTS):
            patch.set_facecolor(COLORS[k])
            patch.set_alpha(0.75)
        ax.set_yscale("log")
        ax.set_xticks(range(1, len(OPTS) + 1), OPTS)
        ax.set(ylabel="iterations", title=f"{NAMES[d]}, 20 splits")
        ax.grid(axis="x", visible=False)
    save(fig, "splits")


def fig_scaling(E):
    dims = [int(d) for d in E["scaling"]]
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.9), layout="constrained")
    for k, marker in zip(OPTS, "osD^v"):
        r = [E["scaling"][str(d)][k] for d in dims]
        axes[0].loglog(dims, [x["time_per_iter"] * 1000 for x in r], marker=marker, mfc="none",
                       color=COLORS[k], lw=1.3, label=k)
        axes[1].loglog(dims, [x["time"] for x in r], marker=marker, mfc="none", color=COLORS[k], lw=1.3, label=k)
    axes[0].set(xlabel="dimension d", ylabel="time per iteration (ms)", title="(a) cost of one iteration")
    axes[1].set(xlabel="dimension d", ylabel="time to ‖∇J‖₂ < 1e-6 (s)", title="(b) time to tolerance")
    axes[1].legend(loc="upper left", bbox_to_anchor=(1.0, 1.0))
    save(fig, "scaling")


def main():
    E = json.loads((ROOT / "results" / "extra.json").read_text())
    lam = {d: r["cv"]["selected"] for d, r in json.loads((ROOT / "results" / "results.json").read_text()).items()}
    (ROOT / "results" / "extra.md").write_text(markdown(E), encoding="utf-8")
    fig_ablation(E)
    fig_order(E, lam)
    fig_splits(E)
    fig_scaling(E)
    print("wrote results/extra.md and figures/{ablation,order,splits,scaling}")


if __name__ == "__main__":
    main()
